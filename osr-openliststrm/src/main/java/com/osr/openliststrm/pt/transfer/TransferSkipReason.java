package com.osr.openliststrm.pt.transfer;

/**
 * 种子这一轮没被转移的原因。
 * <p>
 * 预览页面里，这是用户唯一的解释来源——"为什么我配了规则却没搬走任何东西"。
 * 因此每个原因都对应一个<b>不同的处置动作</b>：调规则、等一等、还是去下载器上看看。
 * 语义相近就合并会让用户查错方向（这一点在自动删种的 CleanSkipReason 上已有先例：
 * "H&R 未达标"与"文件还没传完"必须分开，否则用户会去站点查考核进度而不是看上传队列）。
 * </p>
 *
 * @author Jack
 */
public enum TransferSkipReason {

    /** 种子还没下载完。转移的前提是数据完整，不然目标端校验必然不过 */
    NOT_COMPLETED("尚未下载完成"),

    /** 下载器正忙（校验中/移动中/错误态）。此刻导出或删除种子都可能撞上半截状态 */
    BUSY_STATE("下载器状态不适合转移"),

    /** 目标下载器里已经有这个种子了 */
    ALREADY_ON_TARGET("目标下载器已存在"),

    /** 本规则下这个种子已经有一次转移在校验中，等它出结果 */
    IN_PROGRESS("已有一次转移正在进行"),

    /** 带着规则里的排除标签 */
    EXCLUDED_TAG("命中排除标签"),

    /** 规则限定了只转移带某些标签的种子，而它一个都不带 */
    TAG_NOT_MATCHED("不带规则要求的标签"),

    /** 体积落在规则区间之外 */
    SIZE_NOT_MATCHED("体积不在规则区间内"),

    /** 在源下载器上还没做够规则要求的时长 */
    SEED_TIME_NOT_REACHED("做种时长未达标"),

    /**
     * 对应的下载记录还在 H&R 考核期内。
     * <p>
     * 换了下载器之后做种时长要从零开始重新累计（那是下载器自己的计时口径），
     * OSR 的考核追踪会因此推迟达标；而站点侧的考核并不会因为换客户端而重置，
     * 两边口径一错开就没法再判断"能不能安全删种"。等考核达标了再搬最省事。
     * </p>
     */
    HIT_AND_RUN_PENDING("H&R 考核未达标"),

    /**
     * 这个种子对应的剧集还停在 IN_FLIGHT/UPGRADING——种子下完了，但文件还没传完网盘。
     * <p>
     * 下载追踪认领在途记录时严格按跟踪标签在<b>本下载器</b>里找（认错就是把进度写到别人
     * 头上），此时把种子搬走会让那条记录再也认不回来，最后卡成"下载成功但媒体库里没有"。
     * </p>
     */
    EPISODE_UNSETTLED("对应剧集尚未入库"),

    /** 达到本轮转移上限，留到下一轮 */
    ROUND_LIMIT("超出本轮上限"),

    /**
     * 上一次转移刚失败不久，冷却中。
     * <p>
     * 失败之后源端种子的状态不会变，条件依旧满足，不拦的话下一轮马上原样再试一次。
     * 网络抖动、下载器重启这类一次性故障值得重试，但没必要几分钟一轮——隔几个小时再来。
     * </p>
     */
    RETRY_COOLDOWN("上次失败后冷却中"),

    /**
     * 同一个种子已经失败过太多次，不再自动重试。
     * <p>
     * 与 {@link #RETRY_COOLDOWN} 的处置完全不同：那个等一等就行，这个要人去看失败原因
     * （最常见的是路径映射配错），改完配置删掉失败记录才会重来。合并成一个的话，
     * 用户会一直以为"再等等就好了"。
     * </p>
     */
    TOO_MANY_FAILURES("失败次数过多，已停止重试");

    private final String desc;

    TransferSkipReason(String desc) {
        this.desc = desc;
    }

    public String getDesc() {
        return desc;
    }
}
